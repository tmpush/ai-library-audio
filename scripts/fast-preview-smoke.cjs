const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {spawn,spawnSync}=require('child_process');
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const data=fs.mkdtempSync(path.join(root,'data','fast-ui-check-'));
const model=path.join(data,'test-model');fs.mkdirSync(model);
fs.writeFileSync(path.join(model,'config.json'),'{}');fs.writeFileSync(path.join(model,'model.safetensors'),'fixture, never loaded');
const python=path.join(root,'.venv-tts','Scripts','python.exe');
const child=spawn(python,['-X','utf8','-m','client.preview','--no-browser','--with-samples','--data-dir',data],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
let browser;
(async()=>{
 const url=await new Promise((resolve,reject)=>{let buffer='';const timer=setTimeout(()=>reject(Error('startup timeout')),30000);child.stdout.on('data',chunk=>{buffer+=chunk.toString();const end=buffer.indexOf('\n');if(end>=0){try{resolve(JSON.parse(buffer.slice(0,end)).url);clearTimeout(timer)}catch(e){reject(e)}}});child.on('exit',code=>reject(Error('preview exited '+code)));});
 browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1200,height:1000}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(url);await page.getByRole('button',{name:'Голос и озвучка'}).click();
 await page.getByRole('heading',{name:'Студия озвучки'}).waitFor();
 await page.getByText('Модель и оборудование',{exact:true}).click();
 await page.getByLabel('Папка модели Qwen3-TTS Base').fill(model);
 await page.getByLabel(/^Вычисления/).selectOption('cuda:0');
 await page.getByLabel(/^Режим озвучки/).selectOption('cuda_graphs');
 let response=page.waitForResponse(r=>r.url().endsWith('/settings/model')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Проверить и сохранить',exact:true}).click();
 let settings=await(await response).json();if(settings.backend!=='cuda_graphs')throw Error('fast backend not saved');
 if(await page.getByRole('button',{name:'Озвучить книгу',exact:true}).isEnabled())throw Error('license gate bypassed');
 await page.screenshot({path:path.join(root,'artifacts/fast-studio.png'),fullPage:true});
 await page.getByLabel(/^Вычисления/).selectOption('cpu');
 if(await page.getByLabel(/^Режим озвучки/).inputValue()!=='auto')throw Error('device switch did not reset mode');
 response=page.waitForResponse(r=>r.url().endsWith('/settings/model')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Проверить и сохранить',exact:true}).click();
 settings=await(await response).json();if(settings.backend!=='standard')throw Error('CPU selected CUDA graphs');
 await page.setViewportSize({width:640,height:900});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: accelerated CUDA selection, persisted settings, CPU reset, license gate, 640px layout, no page errors');
})().catch(error=>{console.error(error);process.exitCode=1}).finally(async()=>{
 if(browser)await browser.close();
 spawnSync(python,['-m','client.preview','--stop','--data-dir',data],{cwd:root,windowsHide:true,timeout:10000});
 child.kill();
});
