const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path=require('path');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || 'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173');
 await page.getByLabel('Токен локальной сессии').fill(process.env.BOOKS_LOCAL_TOKEN || 'local-development-session-2026-books');
 await page.getByRole('button',{name:'Открыть библиотеку'}).click();
 await page.getByRole('button',{name:'Добавить книгу'}).waitFor();
 await page.locator('input[type=file]').setInputFiles(path.resolve('samples/night-keeper.fb2'));
 await page.getByRole('heading',{name:'Ночной смотритель'}).waitFor();
 await page.getByLabel('Числа прописью').check();
 await page.getByRole('button',{name:'Подготовить текст',exact:true}).click();
 await page.locator('.prepared').filter({hasText:'двенадцать'}).waitFor();
 await page.getByRole('button',{name:'Показать оригинал'}).click();
 await page.locator('.text-block').nth(2).click();
 await page.getByLabel(/Новая глава с блока/).fill('Проверка границы');
 await page.getByRole('button',{name:'Разделить главу',exact:true}).click();
 await page.getByRole('button',{name:/Проверка границы/}).waitFor();
 fs.mkdirSync('artifacts',{recursive:true});
 await page.screenshot({path:'artifacts/ui-light.png',fullPage:true});
 await page.getByRole('button',{name:'Тёмная тема'}).click();
 await page.screenshot({path:'artifacts/ui-dark.png',fullPage:true});
 await page.setViewportSize({width:640,height:900});
 await page.screenshot({path:'artifacts/ui-small.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('Horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();
 console.log('UI smoke passed: import, normalization, split, themes, 640px layout; no page errors');
})().catch(e=>{console.error(e);process.exit(1)});
